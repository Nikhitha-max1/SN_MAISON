/* =========================
   BAG PAGE
   ========================= */

function renderBag() {

  let el =
    document.querySelector(
      "#bag-list"
    );

  let bag = getBag();

  if (!el) return;


  if (!bag.length) {

    el.innerHTML = `
      <div class="empty">

        <h2>
          Your bag is waiting.
        </h2>

        <p>
          Discover the latest
          SN MAISON pieces.
        </p>

        <a
          class="btn"
          href="shop.html"
        >
          Continue shopping
        </a>

      </div>
    `;


    let total =
      document.querySelector(
        "#bag-total"
      );

    if (total) {

      total.textContent = "₹0";

    }

    return;

  }


  el.innerHTML = bag.map(item => {

    let p =
      products.find(
        x => x.id === item.id
      );


    if (!p) return "";


    return `

      <div class="bag-item">

        <img
          src="${p.img}"
          alt="${p.name}"
        >


        <div>

          <h3>
            ${p.name}
          </h3>

          <div>
            ${money(p.price)}
          </div>

          <p
            style="
              color:#777;
              font-size:12px
            "
          >
            Quantity: ${item.qty}
          </p>


          <button
            class="chip"
            onclick="removeBag(${p.id})"
          >
            Remove
          </button>

        </div>


        <strong>
          ${money(
            p.price * item.qty
          )}
        </strong>

      </div>

    `;

  }).join("");


  let total =
    bag.reduce(
      (s, i) => {

        let p =
          products.find(
            p => p.id === i.id
          );

        return s +
          (p
            ? p.price * i.qty
            : 0
          );

      },
      0
    );


  let totalElement =
    document.querySelector(
      "#bag-total"
    );


  if (totalElement) {

    totalElement.textContent =
      money(total);

  }


  updateCount();

}


/* =========================
   REMOVE FROM BAG
   ========================= */

function removeBag(id) {

  saveBag(
    getBag().filter(
      x => x.id !== id
    )
  );

  renderBag();

}


/* =========================
   SEARCH
   ========================= */

function setupSearch() {

  let form =
    document.querySelector(
      "#search-form"
    );


  if (form) {

    form.onsubmit = e => {

      e.preventDefault();


      let input =
        document.querySelector(
          "#search-input"
        );


      location.href =
        "shop.html?q=" +
        encodeURIComponent(
          input.value
        );

    };

  }

}


