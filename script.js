/* =========================
   RENDER PRODUCTS
   ========================= */

function renderProducts(list, target) {

  let el = document.querySelector(target);

  if (el) {

    el.innerHTML = list
      .map(productCard)
      .join("");

  }
}


/* =========================
   SHOP SETUP
   ========================= */

function setupShop() {

  let list = products;

  let grid = document.querySelector("#shop-grid");

  let chips =
    document.querySelectorAll(
      ".chip[data-cat]"
    );

  if (!grid) return;


  function apply() {

    let active =
      document.querySelector(
        ".chip.active"
      )?.dataset.cat || "All";


    let q =
      (
        document.querySelector(
          "#shop-search"
        )?.value || ""
      ).toLowerCase();


    let sort =
      document.querySelector(
        "#sort"
      )?.value;


    list = products.filter(p =>

      (active === "All" || p.cat === active) &&

      (
        p.name.toLowerCase().includes(q) ||
        p.cat.toLowerCase().includes(q)
      )

    );


    if (sort === "low") {

      list.sort(
        (a, b) => a.price - b.price
      );

    }


    if (sort === "high") {

      list.sort(
        (a, b) => b.price - a.price
      );

    }


    renderProducts(
      list,
      "#shop-grid"
    );

  }


  /*
   * Read category from URL
   *
   * Example:
   * shop.html?cat=Dresses
   */

  let urlCategory =
    new URLSearchParams(
      location.search
    ).get("cat");


  if (urlCategory) {

    let matchingChip =
      document.querySelector(
        `.chip[data-cat="${urlCategory}"]`
      );

    if (matchingChip) {

      chips.forEach(x =>
        x.classList.remove("active")
      );

      matchingChip.classList.add("active");

    }

  }


  chips.forEach(c => {

    c.onclick = () => {

      chips.forEach(x =>
        x.classList.remove("active")
      );

      c.classList.add("active");

      apply();

    };

  });


  document
    .querySelector("#shop-search")
    ?.addEventListener(
      "input",
      apply
    );


  document
    .querySelector("#sort")
    ?.addEventListener(
      "change",
      apply
    );


  apply();

}


