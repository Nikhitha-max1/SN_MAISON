/* =========================
   MONEY FORMAT
   ========================= */

function money(n) {
  return "₹" + n.toLocaleString("en-IN");
}


/* =========================
   BAG
   ========================= */

function getBag() {
  return JSON.parse(
    localStorage.getItem("snmaison-bag") || "[]"
  );
}


function saveBag(b) {
  localStorage.setItem(
    "snmaison-bag",
    JSON.stringify(b)
  );

  updateCount();
}


function updateCount() {
  document.querySelectorAll("[data-count]").forEach(x => {

    x.textContent = getBag().reduce(
      (a, b) => a + b.qty,
      0
    );

  });
}


function addToBag(id) {

  let bag = getBag();

  let item = bag.find(
    x => x.id === id
  );

  if (item) {

    item.qty++;

  } else {

    bag.push({
      id: id,
      qty: 1
    });

  }

  saveBag(bag);

  toast("Added to shopping bag");
}


/* =========================
   TOAST
   ========================= */

function toast(msg) {

  let t = document.getElementById("toast");

  if (!t) {

    t = document.createElement("div");

    t.id = "toast";

    t.style =
      "position:fixed;" +
      "right:20px;" +
      "bottom:20px;" +
      "background:#111;" +
      "color:#fff;" +
      "padding:14px 18px;" +
      "font-size:12px;" +
      "z-index:99;";

    document.body.appendChild(t);
  }

  t.textContent = msg;

  t.style.display = "block";

  setTimeout(() => {
    t.style.display = "none";
  }, 1800);
}


